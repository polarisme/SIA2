function pesos(float|int|string $value): string
{
    return 'P' . money($value);
}

class AisReportPdf extends FPDF
{
    public string $reportTitle = '';
    public string $filtersText = '';

    public function Header(): void
    {
        $this->SetFont('Arial', 'B', 14);
        $this->Cell(0, 8, 'YIELD - ACCOUNTING INFORMATION SYSTEM', 0, 1, 'C');
        $this->SetFont('Arial', 'B', 12);
        $this->Cell(0, 7, iconv('UTF-8', 'ISO-8859-1//TRANSLIT', $this->reportTitle), 0, 1, 'C');
        $this->SetFont('Arial', '', 8);
        $this->Cell(0, 5, 'Generated: ' . date('Y-m-d H:i:s') . '    Generated by: ' . current_username(), 0, 1, 'C');
        if ($this->filtersText !== '') {
            $this->MultiCell(0, 5, iconv('UTF-8', 'ISO-8859-1//TRANSLIT', 'Filters: ' . $this->filtersText), 0, 'L');
        }
        $this->Ln(2);
    }

    public function Footer(): void
    {
        $this->SetY(-12);
        $this->SetFont('Arial', '', 8);
        $this->Cell(0, 8, 'Page ' . $this->PageNo(), 0, 0, 'C');
    }

    public function tableHeader(array $columns, array $widths): void
    {
        $this->SetFillColor(37, 83, 61);
        $this->SetTextColor(255, 255, 255);
        $this->SetFont('Arial', 'B', 8);
        foreach ($columns as $index => $label) {
            $this->Cell($widths[$index], 8, iconv('UTF-8', 'ISO-8859-1//TRANSLIT', $label), 1, 0, 'C', true);
        }
        $this->Ln();
        $this->SetTextColor(36, 51, 45);
        $this->SetFont('Arial', '', 8);
    }

    public function tableRow(array $values, array $widths, array $aligns): void
    {
        foreach ($values as $index => $value) {
            $this->Cell($widths[$index], 7, iconv('UTF-8', 'ISO-8859-1//TRANSLIT', mb_strimwidth((string) $value, 0, 30, '...')), 1, 0, $aligns[$index]);
        }
        $this->Ln();
    }

    public function totalsRow(string $label, array $values, array $widths): void
    {
        $this->SetFont('Arial', 'B', 8);
        $this->SetFillColor(230, 239, 227);
        $this->Cell($widths[0], 7, iconv('UTF-8', 'ISO-8859-1//TRANSLIT', $label), 1, 0, 'L', true);
        foreach ($values as $index => $value) {
            $this->Cell($widths[$index + 1], 7, iconv('UTF-8', 'ISO-8859-1//TRANSLIT', (string) $value), 1, 0, 'R', true);
        }
        $this->Ln();
        $this->SetFont('Arial', '', 8);
    }
}

if (isset($_GET['type'])) {
    $type = (string) $_GET['type'];
    if (!isset($reportTypes[$type])) {
        http_response_code(400);
        exit('Unsupported report type.');
    }
    if (!$pdo instanceof PDO) {
        http_response_code(503);
        exit('Reports are temporarily unavailable because the database could not be reached.');
    }

    $dateFrom = trim((string) ($_GET['date_from'] ?? ''));
    $dateTo = trim((string) ($_GET['date_to'] ?? ''));
    $statusFilter = trim((string) ($_GET['status'] ?? ''));
    foreach (['date_from' => $dateFrom, 'date_to' => $dateTo] as $label => $value) {
        if ($value !== '' && !ais_valid_date($value)) {
            http_response_code(400);
            exit('Invalid report date filter.');
        }
    }
    if ($dateFrom !== '' && $dateTo !== '' && $dateFrom > $dateTo) {
        http_response_code(400);
        exit('Date from must not be later than date to.');
    }

    $appliedFilters = [];
    if ($dateFrom !== '') {
        $appliedFilters[] = 'From ' . $dateFrom;
    }
    if ($dateTo !== '') {
        $appliedFilters[] = 'To ' . $dateTo;
    }

    $pdf = new AisReportPdf('L', 'mm', 'A4');
    $pdf->reportTitle = $reportTypes[$type];
    $pdf->SetMargins(10, 10, 10);
    $pdf->SetAutoPageBreak(true, 16);

    try {
        if ($type === 'income' || $type === 'expense') {
            $transactionType = $type === 'income' ? 'Income' : 'Expense';
            if ($statusFilter !== '' && !in_array($statusFilter, AIS_TRANSACTION_STATUSES, true)) {
                http_response_code(400);
                exit('Invalid status filter.');
            }
            $conditions = ['t.transaction_type = ?', 't.deleted_at IS NULL'];
            $parameters = [$transactionType];
            if ($dateFrom !== '') { $conditions[] = 't.transaction_date >= ?'; $parameters[] = $dateFrom; }
            if ($dateTo !== '') { $conditions[] = 't.transaction_date <= ?'; $parameters[] = $dateTo; }
            if ($statusFilter !== '') { $conditions[] = 't.status = ?'; $parameters[] = $statusFilter; $appliedFilters[] = 'Status: ' . $statusFilter; }
            $statement = $pdo->prepare(
                'SELECT t.transaction_date, t.category, t.description, t.amount, t.payment_method, t.reference_number, f.batch_code, t.status
                 FROM financial_transactions t LEFT JOIN flocks f ON f.flock_id = t.flock_id
                 WHERE ' . implode(' AND ', $conditions) . ' ORDER BY t.transaction_date DESC'
            );
            $statement->execute($parameters);
            $rows = $statement->fetchAll();
            if ($rows === []) { http_response_code(404); exit('No records match the selected report filters.'); }

            $pdf->filtersText = implode('; ', $appliedFilters);
            $pdf->AddPage();
            $columns = ['Date', 'Category', 'Description', 'Amount', 'Payment', 'Reference #', 'Flock/Batch', 'Status'];
            $widths = [25, 40, 62, 28, 30, 32, 30, 30];
            $pdf->tableHeader($columns, $widths);
            $total = 0.0;
            foreach ($rows as $row) {
                $pdf->tableRow(
                    [$row['transaction_date'], $row['category'], (string) $row['description'], pesos($row['amount']), $row['payment_method'], (string) $row['reference_number'], $row['batch_code'] ?? '-', $row['status']],
                    $widths,
                    ['L', 'L', 'L', 'R', 'L', 'L', 'L', 'L']
                );
                if ($row['status'] !== 'Cancelled') {
                    $total += (float) $row['amount'];
                }
            }
            $pdf->totalsRow('TOTAL ' . strtoupper($transactionType) . ' (excl. Cancelled)', [pesos($total)], [array_sum($widths) - 28, 28]);
        } elseif ($type === 'income_expense_summary') {
            $conditions = ["t.status <> 'Cancelled'", 't.deleted_at IS NULL'];
            $parameters = [];
            if ($dateFrom !== '') { $conditions[] = 't.transaction_date >= ?'; $parameters[] = $dateFrom; }
            if ($dateTo !== '') { $conditions[] = 't.transaction_date <= ?'; $parameters[] = $dateTo; }
            $statement = $pdo->prepare(
                'SELECT transaction_type, category, COALESCE(SUM(amount), 0) AS total FROM financial_transactions t
                 WHERE ' . implode(' AND ', $conditions) . ' GROUP BY transaction_type, category ORDER BY transaction_type, total DESC'
            );
            $statement->execute($parameters);
            $rows = $statement->fetchAll();
            if ($rows === []) { http_response_code(404); exit('No records match the selected report filters.'); }

            $pdf->filtersText = implode('; ', $appliedFilters);
            $pdf->AddPage();
            $widths = [140, 137];
            $pdf->tableHeader(['Category', 'Amount'], $widths);
            $totalIncome = 0.0;
            $totalExpense = 0.0;
            $pdf->SetFont('Arial', 'B', 9);
            $pdf->Cell(277, 7, 'INCOME', 1, 1, 'L');
            $pdf->SetFont('Arial', '', 8);
            foreach ($rows as $row) {
                if ($row['transaction_type'] !== 'Income') { continue; }
                $pdf->tableRow([$row['category'], pesos($row['total'])], $widths, ['L', 'R']);
                $totalIncome += (float) $row['total'];
            }
            $pdf->SetFont('Arial', 'B', 9);
            $pdf->Cell(277, 7, 'EXPENSE', 1, 1, 'L');
            $pdf->SetFont('Arial', '', 8);
            foreach ($rows as $row) {
                if ($row['transaction_type'] !== 'Expense') { continue; }
                $pdf->tableRow([$row['category'], pesos($row['total'])], $widths, ['L', 'R']);
                $totalExpense += (float) $row['total'];
            }
            $pdf->totalsRow('TOTAL INCOME', [pesos($totalIncome)], [140, 137]);
            $pdf->totalsRow('TOTAL EXPENSE', [pesos($totalExpense)], [140, 137]);
            $pdf->totalsRow('NET INCOME', [pesos($totalIncome - $totalExpense)], [140, 137]);
        } elseif ($type === 'net_income_summary') {
            $conditions = ["t.status <> 'Cancelled'", 't.deleted_at IS NULL'];
            $parameters = [];
            if ($dateFrom !== '') { $conditions[] = 't.transaction_date >= ?'; $parameters[] = $dateFrom; }
            if ($dateTo !== '') { $conditions[] = 't.transaction_date <= ?'; $parameters[] = $dateTo; }
            $statement = $pdo->prepare(
                "SELECT DATE_FORMAT(transaction_date, '%Y-%m') AS ym, transaction_type, COALESCE(SUM(amount), 0) AS total
                 FROM financial_transactions t WHERE " . implode(' AND ', $conditions) . ' GROUP BY ym, transaction_type ORDER BY ym'
            );
            $statement->execute($parameters);
            $map = [];
            foreach ($statement->fetchAll() as $row) {
                $map[$row['ym']][$row['transaction_type']] = (float) $row['total'];
            }
            if ($map === []) { http_response_code(404); exit('No records match the selected report filters.'); }
            ksort($map);

            $pdf->filtersText = implode('; ', $appliedFilters);
            $pdf->AddPage();
            $widths = [70, 69, 69, 69];
            $pdf->tableHeader(['Month', 'Income', 'Expense', 'Net Income'], $widths);
            $grandIncome = 0.0;
            $grandExpense = 0.0;
            foreach ($map as $ym => $values) {
                $income = $values['Income'] ?? 0.0;
                $expense = $values['Expense'] ?? 0.0;
                $pdf->tableRow([$ym, pesos($income), pesos($expense), pesos($income - $expense)], $widths, ['L', 'R', 'R', 'R']);
                $grandIncome += $income;
                $grandExpense += $expense;
            }
            $pdf->totalsRow('GRAND TOTAL', [pesos($grandIncome), pesos($grandExpense), pesos($grandIncome - $grandExpense)], $widths);
        } elseif ($type === 'ar' || $type === 'ap') {
            if ($statusFilter !== '' && !in_array($statusFilter, AIS_AR_AP_STATUSES, true)) {
                http_response_code(400);
                exit('Invalid status filter.');
            }
            $table = $type === 'ar' ? 'accounts_receivable' : 'accounts_payable';
            $nameColumn = $type === 'ar' ? 'customer_name' : 'supplier_name';
            $nameLabel = $type === 'ar' ? 'Customer' : 'Supplier';
            $statusSql = ar_ap_status_sql();
            $conditions = ['deleted_at IS NULL'];
            $parameters = [];
            if ($dateFrom !== '') { $conditions[] = 'invoice_date >= ?'; $parameters[] = $dateFrom; }
            if ($dateTo !== '') { $conditions[] = 'invoice_date <= ?'; $parameters[] = $dateTo; }
            if ($statusFilter !== '') { $conditions[] = "($statusSql) = ?"; $parameters[] = $statusFilter; $appliedFilters[] = 'Status: ' . $statusFilter; }
            $whereSql = $conditions === [] ? '' : ('WHERE ' . implode(' AND ', $conditions));
            $statement = $pdo->prepare(
                "SELECT $nameColumn AS party_name, invoice_number, invoice_date, due_date, amount_due, amount_paid, balance, ($statusSql) AS live_status
                 FROM $table $whereSql ORDER BY due_date"
            );
            $statement->execute($parameters);
            $rows = $statement->fetchAll();
            if ($rows === []) { http_response_code(404); exit('No records match the selected report filters.'); }

            $pdf->filtersText = implode('; ', $appliedFilters);
            $pdf->AddPage();
            $columns = [$nameLabel, 'Invoice #', 'Invoice Date', 'Due Date', 'Amount Due', 'Amount Paid', 'Balance', 'Status'];
            $widths = [45, 32, 30, 30, 35, 35, 35, 35];
            $pdf->tableHeader($columns, $widths);
            $totalDue = 0.0;
            $totalPaid = 0.0;
            $totalBalance = 0.0;
            foreach ($rows as $row) {
                $pdf->tableRow(
                    [$row['party_name'], (string) $row['invoice_number'], $row['invoice_date'], $row['due_date'], pesos($row['amount_due']), pesos($row['amount_paid']), pesos($row['balance']), $row['live_status']],
                    $widths,
                    ['L', 'L', 'L', 'L', 'R', 'R', 'R', 'L']
                );
                $totalDue += (float) $row['amount_due'];
                $totalPaid += (float) $row['amount_paid'];
                $totalBalance += (float) $row['balance'];
            }
            $pdf->totalsRow('TOTAL', [pesos($totalDue), pesos($totalPaid), pesos($totalBalance), ''], [137, 35, 35, 35, 35]);
        }
    } catch (PDOException $exception) {
        error_log('AIS report query failed: ' . $exception->getMessage());
        http_response_code(500);
        exit('The report could not be generated.');
    }

    $pdf->Output('D', $type . '-report-' . date('Ymd-His') . '.pdf');
    exit;
}

